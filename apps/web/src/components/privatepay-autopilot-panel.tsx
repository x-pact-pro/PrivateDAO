"use client";

import { useState } from "react";
import { useWallet } from "@solana/wallet-adapter-react";
import { KeyRound, Loader2, ShieldCheck } from "lucide-react";

const API_BASE = (process.env.NEXT_PUBLIC_AGENT_EXCHANGE_API_BASE || "https://agents.privatedao.org").replace(/\/$/, "");

type AutopilotStatus = {
  enabled?: boolean;
  blockers?: string[];
  custody?: string;
  reusable_x402_credentials?: boolean;
};

function encodeBase64(bytes: Uint8Array) {
  let binary = "";
  for (const byte of bytes) binary += String.fromCharCode(byte);
  return btoa(binary);
}

function errorText(payload: unknown, status: number) {
  if (payload && typeof payload === "object") {
    const value = payload as { message?: unknown; error?: unknown; code?: unknown };
    const message = typeof value.message === "string" ? value.message : typeof value.error === "string" ? value.error : "";
    if (message) return `${message}${typeof value.code === "string" ? ` (${value.code})` : ""}`;
  }
  return `Autopilot request failed (HTTP ${status}).`;
}

export function PrivatePayAutopilotPanel({ wallet }: { wallet: string }) {
  const { signMessage } = useWallet();
  const [budget, setBudget] = useState("5000000");
  const [maxPerOperation, setMaxPerOperation] = useState("500000");
  const [maxOperations, setMaxOperations] = useState("10");
  const [ttlHours, setTtlHours] = useState("24");
  const [services, setServices] = useState("privatepay.x402");
  const [networks, setNetworks] = useState("solana:5eykt4UsFv8P8NJdTREpY1vzqKqZKvdp");
  const [assets, setAssets] = useState("");
  const [payTo, setPayTo] = useState("");
  const [sessionPublicKey, setSessionPublicKey] = useState("");
  const [sessionSignature, setSessionSignature] = useState("");
  const [challenge, setChallenge] = useState<{ challengeId: string; message: string } | null>(null);
  const [status, setStatus] = useState("No external-agent policy created yet.");
  const [policyId, setPolicyId] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const [autopilot, setAutopilot] = useState<AutopilotStatus | null>(null);
  const [statusLoading, setStatusLoading] = useState(false);

  async function loadStatus() {
    const response = await fetch(`${API_BASE}/api/privatepay/autopilot/status`, { headers: { accept: "application/json" }, cache: "no-store" });
    const payload = await response.json().catch(() => ({}));
    if (!response.ok) throw new Error(errorText(payload, response.status));
    const next = payload as AutopilotStatus;
    setAutopilot(next);
    return next;
  }

  async function createPolicy() {
    if (!wallet || !signMessage) {
      setStatus("Connect a wallet that supports message signing first.");
      return;
    }
    if (!/^\d+$/.test(budget) || !/^\d+$/.test(maxPerOperation) || !/^\d+$/.test(maxOperations) || !/^\d+$/.test(ttlHours)) {
      setStatus("Use integer limits. Amounts are token base units.");
      return;
    }
    const allowedNetworks = networks.split(",").map((value) => value.trim()).filter(Boolean);
    const allowedAssets = assets.split(",").map((value) => value.trim()).filter(Boolean);
    const allowedPayTo = payTo.split(",").map((value) => value.trim()).filter(Boolean);
    if (!allowedNetworks.length || !allowedAssets.length || !allowedPayTo.length) {
      setStatus("Add an explicit network, token mint, and payment recipient allowlist before creating an agent policy.");
      return;
    }
    if (!sessionPublicKey.trim()) {
      setStatus("Paste the public key generated by the external agent before requesting a policy challenge.");
      return;
    }
    if (BigInt(maxPerOperation) > BigInt(budget)) {
      setStatus("The per-operation limit cannot exceed the total budget.");
      return;
    }
    setBusy(true);
    setPolicyId(null);
    try {
      const current = autopilot || await loadStatus();
      if (current.enabled !== true) throw new Error((current.blockers || ["PrivatePAY Autopilot is not enabled on the server."]).join(" "));
      const policy = {
        owner: wallet,
        session_public_key: sessionPublicKey.trim(),
        budget_base_units: budget,
        max_per_operation_base_units: maxPerOperation,
        max_operations: Number(maxOperations),
        ttl_ms: Number(ttlHours) * 60 * 60 * 1000,
        allowed_services: services.split(",").map((value: string) => value.trim()).filter(Boolean),
        allowed_networks: allowedNetworks,
        allowed_assets: allowedAssets,
        allowed_pay_to: allowedPayTo,
      };
      if (!challenge) {
        setStatus("Requesting a bounded challenge for this external agent...");
        const challengeResponse = await fetch(`${API_BASE}/api/privatepay/autopilot/challenge`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify(policy) });
        const challengePayload = await challengeResponse.json().catch(() => ({})) as { challenge_id?: string; message?: string };
        if (!challengeResponse.ok || !challengePayload.challenge_id || !challengePayload.message) throw new Error(errorText(challengePayload, challengeResponse.status));
        setChallenge({ challengeId: challengePayload.challenge_id, message: challengePayload.message });
        setStatus("Send the displayed challenge message to the external agent, then paste its base64 signature and create the policy again.");
        return;
      }
      if (!sessionSignature.trim()) {
        setStatus("Paste the external agent's base64 signature for the displayed challenge before creating the policy.");
        return;
      }
      setStatus("Review the policy in your wallet and approve the owner signature...");
      const ownerSignature = await signMessage(new TextEncoder().encode(challenge.message));
      const policyResponse = await fetch(`${API_BASE}/api/privatepay/autopilot/policies`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ ...policy, challenge_id: challenge.challengeId, owner_signature: encodeBase64(ownerSignature), session_signature: sessionSignature.trim() }) });
      const created = await policyResponse.json().catch(() => ({})) as { policy_id?: string };
      if (!policyResponse.ok || !created.policy_id) throw new Error(errorText(created, policyResponse.status));
      setPolicyId(created.policy_id);
      setChallenge(null);
      setSessionSignature("");
      setStatus("Scoped policy created. The external agent retains its session key; PrivateDAO received only its public key and signatures.");
    } catch (error) {
      setStatus(error instanceof Error ? error.message : "Unable to create the scoped policy.");
    } finally {
      setBusy(false);
    }
  }

  async function refreshStatus() {
    setStatusLoading(true);
    try {
      const current = await loadStatus();
      setStatus(current.enabled === true
        ? "Autopilot is activated. Configure a bounded policy before approving the owner signature."
        : (current.blockers || ["PrivatePAY Autopilot is not enabled on the server."]).join(" "));
    } catch (error) {
      setStatus(error instanceof Error ? error.message : "Unable to read Autopilot status.");
    } finally {
      setStatusLoading(false);
    }
  }

  return <section className="wallet-data-panel p-5 sm:p-6" aria-labelledby="privatepay-autopilot-title">
    <div className="flex items-start justify-between gap-4"><div><h3 id="privatepay-autopilot-title" className="flex items-center gap-2 text-sm font-semibold text-[var(--wallet-text)]"><KeyRound className="h-4 w-4 text-[var(--wallet-success)]" /> Create a bounded agent policy</h3><p className="mt-2 max-w-2xl text-xs leading-5 text-[var(--wallet-secondary)]">A separate session key can authorize only the listed x402 services within these limits. It never receives the wallet private key, and every policy starts with an owner signature.</p></div><ShieldCheck className="h-5 w-5 text-[var(--wallet-secondary)]" aria-hidden="true" /></div>
    <div className="mt-5 grid gap-3 sm:grid-cols-2 lg:grid-cols-4"><label className="text-xs text-[var(--wallet-secondary)]">Budget (base units)<input value={budget} onChange={(event) => setBudget(event.target.value)} disabled={busy || Boolean(challenge)} inputMode="numeric" className="mt-2 min-h-10 w-full border border-[var(--wallet-line)] bg-[var(--wallet-elevated)] px-3 font-mono text-sm text-[var(--wallet-text)]" /></label><label className="text-xs text-[var(--wallet-secondary)]">Max per operation<input value={maxPerOperation} onChange={(event) => setMaxPerOperation(event.target.value)} disabled={busy || Boolean(challenge)} inputMode="numeric" className="mt-2 min-h-10 w-full border border-[var(--wallet-line)] bg-[var(--wallet-elevated)] px-3 font-mono text-sm text-[var(--wallet-text)]" /></label><label className="text-xs text-[var(--wallet-secondary)]">Max operations<input value={maxOperations} onChange={(event) => setMaxOperations(event.target.value)} disabled={busy || Boolean(challenge)} inputMode="numeric" className="mt-2 min-h-10 w-full border border-[var(--wallet-line)] bg-[var(--wallet-elevated)] px-3 font-mono text-sm text-[var(--wallet-text)]" /></label><label className="text-xs text-[var(--wallet-secondary)]">Policy TTL (hours)<input value={ttlHours} onChange={(event) => setTtlHours(event.target.value)} disabled={busy || Boolean(challenge)} inputMode="numeric" className="mt-2 min-h-10 w-full border border-[var(--wallet-line)] bg-[var(--wallet-elevated)] px-3 font-mono text-sm text-[var(--wallet-text)]" /></label></div>
    <label className="mt-3 block text-xs text-[var(--wallet-secondary)]">External agent session public key<input value={sessionPublicKey} onChange={(event) => setSessionPublicKey(event.target.value)} disabled={busy || Boolean(challenge)} spellCheck={false} placeholder="Generated and retained by Grok, Telegram, MCP, or another agent" className="mt-2 min-h-10 w-full border border-[var(--wallet-line)] bg-[var(--wallet-elevated)] px-3 font-mono text-xs text-[var(--wallet-text)]" /></label>
    <label className="mt-3 block text-xs text-[var(--wallet-secondary)]">Allowed service IDs<input value={services} onChange={(event) => setServices(event.target.value)} disabled={busy || Boolean(challenge)} spellCheck={false} className="mt-2 min-h-10 w-full border border-[var(--wallet-line)] bg-[var(--wallet-elevated)] px-3 font-mono text-xs text-[var(--wallet-text)]" /></label>
    <div className="mt-3 grid gap-3 sm:grid-cols-3"><label className="text-xs text-[var(--wallet-secondary)]">Allowed networks<input value={networks} onChange={(event) => setNetworks(event.target.value)} disabled={busy || Boolean(challenge)} spellCheck={false} placeholder="solana:..." className="mt-2 min-h-10 w-full border border-[var(--wallet-line)] bg-[var(--wallet-elevated)] px-3 font-mono text-xs text-[var(--wallet-text)]" /></label><label className="text-xs text-[var(--wallet-secondary)]">Allowed token mints<input value={assets} onChange={(event) => setAssets(event.target.value)} disabled={busy || Boolean(challenge)} spellCheck={false} placeholder="Token mint address" className="mt-2 min-h-10 w-full border border-[var(--wallet-line)] bg-[var(--wallet-elevated)] px-3 font-mono text-xs text-[var(--wallet-text)]" /></label><label className="text-xs text-[var(--wallet-secondary)]">Allowed payment recipients<input value={payTo} onChange={(event) => setPayTo(event.target.value)} disabled={busy || Boolean(challenge)} spellCheck={false} placeholder="Exact recipient address" className="mt-2 min-h-10 w-full border border-[var(--wallet-line)] bg-[var(--wallet-elevated)] px-3 font-mono text-xs text-[var(--wallet-text)]" /></label></div>
    {challenge ? <div className="mt-3 border border-[var(--wallet-line)] bg-[var(--wallet-bg)] p-4"><div className="flex items-start justify-between gap-3"><p className="text-xs leading-5 text-[var(--wallet-secondary)]">Have the external agent sign this exact challenge with its session key. Do not send its private key.</p><button type="button" onClick={() => void navigator.clipboard?.writeText(challenge.message)} className="shrink-0 border border-[var(--wallet-line)] px-3 py-2 text-xs font-semibold text-[var(--wallet-text)]">Copy challenge</button></div><pre className="mt-3 max-h-32 overflow-auto whitespace-pre-wrap break-all border border-[var(--wallet-line)] p-3 font-mono text-[11px] text-[var(--wallet-muted)]">{challenge.message}</pre><label className="mt-3 block text-xs text-[var(--wallet-secondary)]">Agent signature (base64)<textarea value={sessionSignature} onChange={(event) => setSessionSignature(event.target.value)} disabled={busy} rows={3} spellCheck={false} className="mt-2 w-full border border-[var(--wallet-line)] bg-[var(--wallet-elevated)] p-3 font-mono text-xs text-[var(--wallet-text)]" /></label></div> : null}
    <div className="mt-4 flex flex-wrap items-center gap-3"><button type="button" onClick={() => void refreshStatus()} disabled={busy || statusLoading} className="inline-flex min-h-10 items-center gap-2 border border-[var(--wallet-line)] px-3 text-xs font-semibold text-[var(--wallet-text)] disabled:opacity-50">{statusLoading ? <Loader2 className="h-4 w-4 animate-spin" /> : <ShieldCheck className="h-4 w-4" />} Check activation</button><button type="button" onClick={() => void createPolicy()} disabled={busy || !wallet || autopilot?.enabled !== true} className="inline-flex min-h-10 items-center gap-2 bg-[var(--wallet-text)] px-3 text-xs font-semibold text-[var(--wallet-bg)] disabled:opacity-50">{busy ? <Loader2 className="h-4 w-4 animate-spin" /> : <KeyRound className="h-4 w-4" />} Create signed policy</button>{policyId ? <span className="font-mono text-xs text-[var(--wallet-success)]">{policyId}</span> : null}</div>
    <div role="status" aria-live="polite" className="mt-4 border border-[var(--wallet-line)] bg-[var(--wallet-bg)] px-4 py-3 text-xs leading-5 text-[var(--wallet-secondary)]">{status}</div>
  </section>;
}
